-- e-Tax Invoice & e-Receipt (ใบกำกับภาษีอิเล็กทรอนิกส์) — ETDA ขมธอ. 3-2560, ประกาศอธิบดีกรมสรรพากรฯ (ฉบับที่ 196)

-- The seller profile is this module's own data (never read from identity's tables). One row per company.
-- The PKCS#12 file is stored as uploaded (it is encrypted by its own password); the password is NEVER stored.
create table etax_settings (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null unique,
  seller_name text,
  tax_id text,
  branch text not null default '00000' check (branch ~ '^[0-9]{5}$'),
  building_number text,
  address_line1 text,
  address_line2 text,
  subdistrict text,
  subdistrict_code text,
  district text,
  district_code text,
  province text,
  province_code text,
  postcode text,
  email text,
  phone text,
  invoice_type_code text not null default 'T02' check (invoice_type_code in ('388', 'T02')),
  p12 bytea,
  p12_file_name text,
  cert_subject text,
  cert_issuer text,
  cert_serial text,
  cert_not_before timestamptz,
  cert_not_after timestamptz,
  cert_fingerprint text,
  cert_uploaded_at timestamptz,
  cert_uploaded_by_name text,
  updated_at timestamptz not null default now(),
  updated_by_name text
);
-- @tenant etax_settings

-- One snapshot per tax invoice / credit note / debit note received from sales (unique per source document).
create table etax_documents (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null,
  source text not null check (source in ('invoice', 'note')),
  source_id uuid not null,
  kind text not null check (kind in ('invoice', 'credit', 'debit')),
  doc_no text not null,
  issue_date date not null,
  due_date date,
  type_code text check (type_code in ('388', 'T02', '80', '81')),
  buyer_id uuid,
  buyer_name text not null,
  buyer_tax_id text,
  buyer_branch text,
  buyer_address text,
  buyer_email text,
  buyer_edited_by_name text,
  -- null = an old sales.invoiced payload without lines: status 'incomplete', cannot be generated
  lines jsonb,
  net numeric(18,4) not null,
  vat numeric(18,4) not null,
  gross numeric(18,4) not null,
  vat_mode text,
  deposit jsonb,
  ref_invoice_id uuid,
  ref_invoice_no text,
  ref_invoice_date date,
  reason text,
  original_net numeric(18,4),
  correct_net numeric(18,4),
  purpose_code text,
  status text not null check (status in ('incomplete', 'draft', 'generated', 'signed', 'sent_manual', 'sent_sp')),
  problems jsonb not null default '[]',
  warnings jsonb not null default '[]',
  xml text,
  xml_sha256 text,
  generated_at timestamptz,
  generated_by_name text,
  signed_xml text,
  signed_sha256 text,
  signed_at timestamptz,
  signed_by_name text,
  signing_cert_serial text,
  signing_cert_subject text,
  sent_channel text check (sent_channel in ('email_etda', 'service_provider')),
  sent_date date,
  sent_reference text,
  sent_note text,
  sent_recorded_at timestamptz,
  sent_by_name text,
  payload jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, source, source_id)
);
-- @tenant etax_documents
create index etax_documents_by_date on etax_documents (tenant_id, issue_date desc, doc_no desc);
create index etax_documents_by_ref on etax_documents (tenant_id, ref_invoice_id);
