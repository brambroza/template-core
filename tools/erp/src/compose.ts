import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { ModuleManifest } from '@erp/kernel';

const dbName = (id: string) => `erp_${id.replace(/-/g, '_')}`;

/** The backup script the `backup` container runs (tools/erp/assets/erp-backup.sh — see its header for the commands). */
const BACKUP_SCRIPT = new URL('../assets/erp-backup.sh', import.meta.url);

/** Error reporting (Sentry) settings every module and the gateway receive; empty DSN = off. */
const SENTRY_ENV = '      SENTRY_DSN: ${SENTRY_DSN:-}\n      SENTRY_ENVIRONMENT: ${SENTRY_ENVIRONMENT:-production}\n';

/**
 * Off-site copy loop of the `backup-offsite` container (rclone): every hour, ./backups → the Spaces/S3 bucket. `copy` never
 * deletes there (retention = a lifecycle rule on the bucket); partial folders (".partial-…") and restore logs are skipped.
 * `$$` is compose's escape for a literal `$` (the variables are read by the container's shell, not by compose).
 */
const OFFSITE_LOOP = [
  'while true; do',
  '  if [ -n "$$BACKUP_S3_BUCKET" ]; then',
  `    rclone copy /backups "offsite:$$BACKUP_S3_BUCKET/$$BACKUP_S3_PREFIX" --exclude '.*' --exclude '.*/**' --s3-no-check-bucket && echo "offsite copy ok" || echo "offsite copy FAILED"`,
  '  fi',
  '  sleep 3600',
  'done',
].map((l) => `        ${l}`).join('\n');

/**
 * Generate a docker-compose installation for the selected modules:
 * one Postgres (a separate database per module), one container per module, and the gateway on :8080.
 */
export function compose(selection: string[], manifests: ModuleManifest[], outDir: string, buildContext: string): string[] {
  mkdirSync(outDir, { recursive: true });
  const ctx = relative(outDir, buildContext) || '.';
  const mods = selection.map((id) => manifests.find((m) => m.id === id)!);
  const svc = (m: ModuleManifest) => `  ${m.id}:
    build: { context: ${ctx}, args: { APP_DIR: services/${m.id} } }
    restart: unless-stopped
    depends_on: [postgres]
    environment:
      DATABASE_URL: postgres://erp_app:\${APP_DB_PASSWORD}@postgres:5432/${dbName(m.id)}
      JWT_SECRET: \${JWT_SECRET}
      INTERNAL_TOKEN: \${INTERNAL_TOKEN}
      EVENT_ROUTER_URL: http://gateway:8080/_events/publish
      ERP_LICENSE: \${ERP_LICENSE}
      LOG_LEVEL: info
${SENTRY_ENV}${m.id === 'sales' ? '      PROMPTPAY_ID: ${PROMPTPAY_ID:-}\n' : ''}${m.id === 'identity' ? '      APP_URL: ${PUBLIC_APP_URL:-}\n      OPS_TENANT_CODE: ${OPS_TENANT_CODE:-}\n      EMAIL_PROVIDER: ${EMAIL_PROVIDER:-}\n      EMAIL_FROM: ${EMAIL_FROM:-}\n      RESEND_API_KEY: ${RESEND_API_KEY:-}\n      SENDGRID_API_KEY: ${SENDGRID_API_KEY:-}\n      TURNSTILE_SECRET: ${TURNSTILE_SECRET:-}\n      TURNSTILE_SITE_KEY: ${TURNSTILE_SITE_KEY:-}\n' : ''}${m.id === 'automation' ? '      LINE_CHANNEL_ACCESS_TOKEN: ${LINE_CHANNEL_ACCESS_TOKEN:-}\n      LINE_CHANNEL_SECRET: ${LINE_CHANNEL_SECRET:-}\n      LINE_OA_ID: ${LINE_OA_ID:-}\n      PUBLIC_BASE_URL: ${PUBLIC_BASE_URL:-}\n      PUBLIC_APP_URL: ${PUBLIC_APP_URL:-}\n      WEBHOOK_SECRET: ${WEBHOOK_SECRET:-}\n' : ''}`;
  const yml = `# Generated by \`pnpm erp compose ${selection.filter((id) => mods.find((m) => m.id === id)!.tier === 'feature').join(',')}\`
# Modules: ${selection.join(', ')}
services:
  postgres:
    image: postgres:16
    restart: unless-stopped
    environment:
      POSTGRES_PASSWORD: \${POSTGRES_PASSWORD}
      APP_DB_PASSWORD: \${APP_DB_PASSWORD}
    volumes:
      - pgdata:/var/lib/postgresql/data
      - ./init-db.sh:/docker-entrypoint-initdb.d/init-db.sh:ro

${mods.map(svc).join('\n')}
  gateway:
    build: { context: ${ctx}, args: { APP_DIR: apps/gateway } }
    restart: unless-stopped
    depends_on: [${mods.map((m) => m.id).join(', ')}]
    ports: ["8080:8080"]
    environment:
      PORT: 8080
      INTERNAL_TOKEN: \${INTERNAL_TOKEN}
      MODULES: ${mods.map((m) => `${m.id}=http://${m.id}:3000`).join(',')}
${SENTRY_ENV}
  web:
    build: { context: ${ctx}, args: { APP_DIR: apps/web } }
    restart: unless-stopped
    depends_on: [gateway]
    ports: ["3000:3000"]
    environment:
      PORT: 3000
      GATEWAY_URL: http://gateway:8080
      # AI assistant (optional): the customer's own Claude API key
      ANTHROPIC_API_KEY: \${ANTHROPIC_API_KEY:-}
      ANTHROPIC_MODEL: \${ANTHROPIC_MODEL:-}
      COMPANY_NAME: \${COMPANY_NAME:-}

  # daily pg_dump of every database + restore test, kept BACKUP_KEEP_DAYS days in ./backups (see erp-backup.sh)
  backup:
    image: postgres:16-alpine
    restart: unless-stopped
    depends_on: [postgres]
    command: ["erp-backup", "loop"]
    environment:
      PGHOST: postgres
      PGUSER: postgres
      PGPASSWORD: \${POSTGRES_PASSWORD}
      TZ: ICT-7
      BACKUP_AT: \${BACKUP_AT:-0200}
      BACKUP_KEEP_DAYS: \${BACKUP_KEEP_DAYS:-14}
      BACKUP_PING_URL: \${BACKUP_PING_URL:-}
    volumes:
      - ./backups:/backups
      - ./erp-backup.sh:/usr/local/bin/erp-backup:ro

  # copies ./backups to a private DigitalOcean Spaces (or any S3) bucket every hour; off while BACKUP_S3_BUCKET is empty
  backup-offsite:
    image: rclone/rclone:1.68
    restart: unless-stopped
    entrypoint: ["/bin/sh", "-c"]
    command:
      - |
${OFFSITE_LOOP}
    environment:
      RCLONE_CONFIG_OFFSITE_TYPE: s3
      RCLONE_CONFIG_OFFSITE_PROVIDER: \${BACKUP_S3_PROVIDER:-DigitalOcean}
      RCLONE_CONFIG_OFFSITE_ENDPOINT: \${BACKUP_S3_ENDPOINT:-sgp1.digitaloceanspaces.com}
      RCLONE_CONFIG_OFFSITE_ACCESS_KEY_ID: \${BACKUP_S3_KEY:-}
      RCLONE_CONFIG_OFFSITE_SECRET_ACCESS_KEY: \${BACKUP_S3_SECRET:-}
      RCLONE_CONFIG_OFFSITE_ACL: private
      BACKUP_S3_BUCKET: \${BACKUP_S3_BUCKET:-}
      BACKUP_S3_PREFIX: \${BACKUP_S3_PREFIX:-erp}
    volumes:
      - ./backups:/backups:ro

volumes:
  pgdata:
`;
  const init = `#!/bin/bash
# Runs once when the Postgres volume is created: an unprivileged app role (row-level security
# applies to it) and one database per module.
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<SQL
create role erp_app login password '$APP_DB_PASSWORD';
${mods.map((m) => `create database ${dbName(m.id)} owner erp_app;`).join('\n')}
SQL
`;
  const env = `# Copy to .env and change every value. Generate secrets with: openssl rand -hex 32
# The services REFUSE TO START while JWT_SECRET / INTERNAL_TOKEN still hold the example values below
# (whoever knows JWT_SECRET can sign in as anyone). Put the installation behind HTTPS (reverse proxy) before real data.
POSTGRES_PASSWORD=change-me
APP_DB_PASSWORD=change-me-too
JWT_SECRET=${'replace-with-64-random-characters'}
INTERNAL_TOKEN=replace-with-another-random-string
# License token from GO Along (\`dev\` only works outside NODE_ENV=production)
ERP_LICENSE=
PROMPTPAY_ID=
# Optional: AI assistant (⌘K "ถาม AI") — the company's own Claude API key
ANTHROPIC_API_KEY=
ANTHROPIC_MODEL=
COMPANY_NAME=
# Public address of the web app (links in sign-up / password-reset e-mails; required for them in production)
${selection.includes('automation') ? '' : 'PUBLIC_APP_URL=https://erp.example.co.th\n'}# E-mail for sign-up and password reset: resend | sendgrid (unset = printed to the identity log only)
EMAIL_PROVIDER=
EMAIL_FROM=GO Along <no-reply@example.co.th>
RESEND_API_KEY=
SENDGRID_API_KEY=
# Cloud back office: company code of GO Along's own company (its staff get the role with: pnpm erp plan grant-ops <email>)
OPS_TENANT_CODE=
# Cloudflare Turnstile on the public sign-up / forgot-password forms: set BOTH keys of the widget (Cloudflare dashboard → Turnstile).
# The web app reads the site key from identity at run time — no rebuild. Both empty = no CAPTCHA.
TURNSTILE_SITE_KEY=
TURNSTILE_SECRET=
# Error reporting: Sentry project DSN (empty = off). Only error type/stack, module, route and company/user ids are sent.
SENTRY_DSN=
SENTRY_ENVIRONMENT=production
# Backups (container "backup"): daily time HHMM Thai time, days kept on this server, and a heartbeat URL called after every
# good backup + restore test (healthchecks.io or an UptimeRobot heartbeat monitor: alert when it stops)
BACKUP_AT=0200
BACKUP_KEEP_DAYS=14
BACKUP_PING_URL=
# Off-site copy (container "backup-offsite") to a PRIVATE DigitalOcean Spaces bucket; empty bucket = off
BACKUP_S3_BUCKET=
BACKUP_S3_PREFIX=erp
BACKUP_S3_ENDPOINT=sgp1.digitaloceanspaces.com
BACKUP_S3_KEY=
BACKUP_S3_SECRET=
${selection.includes('automation') ? '# Automation: LINE Messaging API (personal alerts + webhook), public URLs, and a secret to sign outgoing webhooks\nLINE_CHANNEL_ACCESS_TOKEN=\nLINE_CHANNEL_SECRET=\nLINE_OA_ID=\nPUBLIC_BASE_URL=https://erp.example.co.th\nPUBLIC_APP_URL=https://erp.example.co.th\nWEBHOOK_SECRET=\n' : ''}`;
  const readme = `# ERP installation: ${selection.join(', ')}

1. \`cp .env.example .env\` and fill in every value (put the license token in ERP_LICENSE).
2. \`docker compose up -d --build\`
3. Create the first company (run once):
   \`\`\`
   docker compose exec identity node -e "fetch('http://localhost:3000/tenants',{method:'POST',headers:{'content-type':'application/json','x-internal-token':process.env.INTERNAL_TOKEN},body:JSON.stringify({code:'mycompany',name:'My Company',admin:{email:'admin@mycompany.co.th',name:'Admin',password:'change-me-now'}})}).then(r=>r.text()).then(console.log)"
   \`\`\`
4. Open http://localhost:3000 and log in with company code \`mycompany\`, \`admin@mycompany.co.th\`, \`change-me-now\`
   — use your own strong password in step 3 instead of \`change-me-now\` (there is no "change password" screen yet).
   (API directly: \`POST http://localhost:8080/api/identity/auth/login\`; installed modules: \`GET http://localhost:8080/api/_catalog\`)
5. Mobile app: point it at \`http://<server-ip>:8080\` (field "ที่อยู่เซิร์ฟเวอร์" on the login screen)

## Monitoring
- Uptime: an UptimeRobot keyword monitor (keyword \`"status":"ok"\`, every 5 minutes) on \`https://<your host>/api/_health\`.
  It answers 200 only when every module and its database answer; a 503 names the module that is down.
- Errors: put the Sentry project DSN in SENTRY_DSN, then \`docker compose up -d\`.

## Backups
The \`backup\` container dumps every database each night at BACKUP_AT into \`./backups/<stamp>/\`, restores each dump into a
scratch database to prove it is usable, keeps BACKUP_KEEP_DAYS days, then calls BACKUP_PING_URL. \`backup-offsite\` copies the
folder to Spaces every hour when BACKUP_S3_BUCKET is set.
\`\`\`
docker compose exec backup erp-backup now      # back up right away
docker compose exec backup erp-backup list
docker compose exec backup erp-backup check    # restore drill of the newest backup (touches nothing live)
\`\`\`
A real restore REPLACES the live data. Stop the ERP services first, restore, start them again:
\`\`\`
docker compose stop ${[...mods.map((m) => m.id), 'gateway', 'web'].join(' ')}
docker compose exec backup erp-backup restore <stamp> --yes      # or only some databases: … --yes erp_sales
docker compose start
\`\`\`
On a new server: copy the backup folder from Spaces into ./backups, \`docker compose up -d postgres backup\`, then restore.
`;
  const files = { 'docker-compose.yml': yml, 'init-db.sh': init, '.env.example': env, 'README.md': readme, 'erp-backup.sh': readFileSync(BACKUP_SCRIPT, 'utf8') };
  for (const [name, content] of Object.entries(files)) writeFileSync(join(outDir, name), content, { mode: name.endsWith('.sh') ? 0o755 : 0o644 });
  return Object.keys(files).map((f) => join(outDir, f));
}
