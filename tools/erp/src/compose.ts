import { mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { ModuleManifest } from '@erp/kernel';

const dbName = (id: string) => `erp_${id.replace(/-/g, '_')}`;

/**
 * Generate a docker-compose installation for the selected modules:
 * one Postgres (a separate database per module), one container per module, and the gateway on :8080.
 */
export function compose(selection: string[], manifests: ModuleManifest[], outDir: string, buildContext: string): string[] {
  mkdirSync(outDir, { recursive: true });
  const ctx = relative(outDir, buildContext) || '.';
  const mods = selection.map((id) => manifests.find((m) => m.id === id)!);
  const svc = (m: ModuleManifest) => `  ${m.id}:
    build: { context: ${ctx}, args: { APP_DIR: services/${m.id} } }
    restart: unless-stopped
    depends_on: [postgres]
    environment:
      DATABASE_URL: postgres://erp_app:\${APP_DB_PASSWORD}@postgres:5432/${dbName(m.id)}
      JWT_SECRET: \${JWT_SECRET}
      INTERNAL_TOKEN: \${INTERNAL_TOKEN}
      EVENT_ROUTER_URL: http://gateway:8080/_events/publish
      ERP_LICENSE: \${ERP_LICENSE}
      LOG_LEVEL: info
${m.id === 'sales' ? '      PROMPTPAY_ID: ${PROMPTPAY_ID:-}\n' : ''}`;
  const yml = `# Generated by \`pnpm erp compose ${selection.filter((id) => mods.find((m) => m.id === id)!.tier === 'feature').join(',')}\`
# Modules: ${selection.join(', ')}
services:
  postgres:
    image: postgres:16
    restart: unless-stopped
    environment:
      POSTGRES_PASSWORD: \${POSTGRES_PASSWORD}
      APP_DB_PASSWORD: \${APP_DB_PASSWORD}
    volumes:
      - pgdata:/var/lib/postgresql/data
      - ./init-db.sh:/docker-entrypoint-initdb.d/init-db.sh:ro

${mods.map(svc).join('\n')}
  gateway:
    build: { context: ${ctx}, args: { APP_DIR: apps/gateway } }
    restart: unless-stopped
    depends_on: [${mods.map((m) => m.id).join(', ')}]
    ports: ["8080:8080"]
    environment:
      PORT: 8080
      INTERNAL_TOKEN: \${INTERNAL_TOKEN}
      MODULES: ${mods.map((m) => `${m.id}=http://${m.id}:3000`).join(',')}

volumes:
  pgdata:
`;
  const init = `#!/bin/bash
# Runs once when the Postgres volume is created: an unprivileged app role (row-level security
# applies to it) and one database per module.
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<SQL
create role erp_app login password '$APP_DB_PASSWORD';
${mods.map((m) => `create database ${dbName(m.id)} owner erp_app;`).join('\n')}
SQL
`;
  const env = `# Copy to .env and change every value.
POSTGRES_PASSWORD=change-me
APP_DB_PASSWORD=change-me-too
JWT_SECRET=${'replace-with-64-random-characters'}
INTERNAL_TOKEN=replace-with-another-random-string
# License token from GO Along (\`dev\` only works outside NODE_ENV=production)
ERP_LICENSE=
PROMPTPAY_ID=
`;
  const readme = `# ERP installation: ${selection.join(', ')}

1. \`cp .env.example .env\` and fill in every value (put the license token in ERP_LICENSE).
2. \`docker compose up -d --build\`
3. Create the first company (run once):
   \`\`\`
   docker compose exec identity node -e "fetch('http://localhost:3000/tenants',{method:'POST',headers:{'content-type':'application/json','x-internal-token':process.env.INTERNAL_TOKEN},body:JSON.stringify({code:'mycompany',name:'My Company',admin:{email:'admin@mycompany.co.th',name:'Admin',password:'change-me-now'}})}).then(r=>r.text()).then(console.log)"
   \`\`\`
4. Log in: \`POST http://localhost:8080/api/identity/auth/login\` with \`{"tenant":"mycompany","email":"admin@mycompany.co.th","password":"change-me-now"}\`
5. Installed modules: \`GET http://localhost:8080/api/_catalog\`
`;
  const files = { 'docker-compose.yml': yml, 'init-db.sh': init, '.env.example': env, 'README.md': readme };
  for (const [name, content] of Object.entries(files)) writeFileSync(join(outDir, name), content, { mode: name.endsWith('.sh') ? 0o755 : 0o644 });
  return Object.keys(files).map((f) => join(outDir, f));
}
