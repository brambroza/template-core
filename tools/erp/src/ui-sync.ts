import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** Front-end apps that render module screens. */
export const UI_APPS = ['apps/web', 'apps/mobile'];

const ident = (id: string) => id.replace(/-(.)/g, (_, c: string) => c.toUpperCase()) + 'Ui';

/** Modules (in `ids`) with a customer screen extension `services/<id>/ext/ui.ts`. */
export function uiExtensions(root: string, ids: string[]): string[] {
  return ids.filter((id) => existsSync(join(root, 'services', id, 'ext', 'ui.ts'))).sort();
}

function render(ids: string[], exts: string[] = []): { ts: string; json: string } {
  const ext = new Set(exts.filter((id) => ids.includes(id)));
  const extIdent = (id: string) => ident(id) + 'Ext';
  const ts = `// Generated by \`pnpm erp ui-sync\` — do not edit. Lists the modules whose screens this app includes${ext.size ? ',\n// merged with the customer extensions in services/<module>/ext/ui.ts' : ''}.
import ${ext.size ? '{ extendUi, type ModuleUi }' : 'type { ModuleUi }'} from '@erp/ui-schema';
${ids.map((id) => `import ${ident(id)} from '@erp/svc-${id}/ui';${ext.has(id) ? `\nimport ${extIdent(id)} from '@erp/svc-${id}/ext/ui';` : ''}`).join('\n')}

export const moduleUis: ModuleUi[] = [${ids.map((id) => (ext.has(id) ? `extendUi(${ident(id)}, ${extIdent(id)})` : ident(id))).join(', ')}];
`;
  const json = JSON.stringify({ packages: ids.map((id) => `@erp/svc-${id}`) }, null, 2) + '\n';
  return { ts, json };
}

/** Modules (in `ids`) that ship screens. */
export function uiModules(root: string, ids: string[]): string[] {
  return ids.filter((id) => existsSync(join(root, 'services', id, 'src', 'ui.ts'))).sort();
}

/** Write each app's module registry + package.json dependencies for exactly these modules. */
export function syncUi(root: string, ids: string[]): string[] {
  const mods = uiModules(root, ids);
  const { ts, json } = render(mods, uiExtensions(root, ids));
  const written: string[] = [];
  for (const app of UI_APPS) {
    const dir = join(root, app);
    if (!existsSync(join(dir, 'package.json'))) continue;
    writeFileSync(join(dir, 'src', 'modules.generated.ts'), ts);
    writeFileSync(join(dir, 'src', 'modules.json'), json);
    const pkgPath = join(dir, 'package.json');
    const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
    const deps = Object.fromEntries(Object.entries<string>(pkg.dependencies ?? {}).filter(([k]) => !k.startsWith('@erp/svc-')));
    for (const id of mods) deps[`@erp/svc-${id}`] = 'workspace:*';
    pkg.dependencies = Object.fromEntries(Object.entries(deps).sort(([a], [b]) => a.localeCompare(b)));
    writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
    written.push(app);
  }
  return written;
}

/** For `verify`: apps whose registry does not match the modules present. */
export function uiOutOfSync(root: string, ids: string[]): string[] {
  const expected = render(uiModules(root, ids), uiExtensions(root, ids)).ts;
  return UI_APPS.filter((app) => existsSync(join(root, app, 'package.json')))
    .filter((app) => !existsSync(join(root, app, 'src', 'modules.generated.ts')) || readFileSync(join(root, app, 'src', 'modules.generated.ts'), 'utf8') !== expected);
}
